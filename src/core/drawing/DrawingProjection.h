#pragma once

// Hidden-line-removed projection for 2D drawings (D0+). GUI-free core code.
//
// Confines every HLRBRep type to DrawingProjection.cpp, the FemMesher
// discipline: this header exposes only plain data (glm/std + TopoDS_Shape) so
// the drawing document, RPCs and tests never see HLR headers. Each projected
// curve carries a SourceRef back to the generating 3D edge (sharp/smooth
// edges) or generating face (silhouettes) — the traceability that drawing
// dimensions attach to.

#include <TopoDS_Shape.hxx>

#include <glm/glm.hpp>

#include <cstdint>
#include <functional>
#include <memory>
#include <optional>
#include <string>
#include <vector>

namespace drawing {

// One body to project: an untransformed shape plus its placement (identity
// for a part's bodies; the occurrence transform for assembly sources).
struct InputBody {
  TopoDS_Shape shape;
  glm::dmat4 transform{1.0};
  // Caller-defined stable id carried through to SourceRef.sourceId — a body's
  // featureId for parts, an occurrence id for assemblies.
  uint64_t sourceId = 0;
  // Invalidate even when a caller edits geometry in place. Shapes must remain
  // immutable between revisions while retained by a cache.
  uint64_t geometryRevision = 0;
  // Which SEMANTIC thing this body belongs to, for cost attribution only: an
  // occurrence usually owns several bodies, and "what would hiding this cost
  // me" is asked about the occurrence. Pairs BETWEEN two bodies of the same
  // group are charged once, not twice — that double count made one driver
  // read as 113% of its own view. 0 falls back to `sourceId`. Never part of
  // the cache key: two placements of one part share their projection.
  uint64_t groupId = 0;
};

// How a projected curve came to exist. Sharp/Smooth/Sewn curves are images of
// real 3D edges; an Outline (silhouette) is generated by the projection and
// has no source edge — only the face whose horizon it is. A Bend line is not
// projected at all: it is a flat sheet-metal crease, drawn from the bend the
// feature recorded, because a flat blank has no edge there to project.
enum class CurveKind { Sharp, Smooth, Sewn, Outline, Bend };

// Where a projected curve came from, in *index* space: edge indices follow
// the deduplicated TopExp::MapShapes(TopAbs_EDGE) order and face indices the
// explorer order — the same contracts ElementMap keys on (ElementMap.h), so
// callers join these to MappedNames without this header knowing Documents.
struct SourceRef {
  uint64_t sourceId = 0;
  int edgeIndex = -1; // sharp/smooth/sewn: the generating 3D edge
  int faceIndex = -1; // outline: the silhouette's generating face
  [[nodiscard]] bool IsResolved() const {
    return edgeIndex >= 0 || faceIndex >= 0;
  }
};

// WHICH HLR, and it is a real choice rather than a quality knob.
//
// Exact runs OCC's curve-based algorithm and is the deliverable: every curve
// carries a SourceRef back to the 3D edge that made it, which is what a
// drawing dimension attaches to. It is also where the cost is, and the cost is
// about SHAPES rather than about how many of them there are:
//
//   16 boxes with a bore, one view      3.1 ms   (linear in bodies)
//   ONE box + a 4-turn helical spring   6.4 s
//   the single-cylinder engine          85.1 s
//   ...the same engine, 2 valves hidden  0.0 s
//
// Two occurrences are the whole bill. HLRBRep_Algo::Hide() intersects every
// projected edge against every face, and a swept B-spline surface — a spring,
// a pipe, a loft — is orders of magnitude dearer to intersect than a plane or
// a cylinder. So an assembly of prismatic parts draws instantly however many
// there are, and one spring does not
// (docs/drawings/README.md#projection-hlr).
//
// Poly runs the same algorithm over the shapes' TRIANGULATIONS. It is orders
// of magnitude cheaper and it is a LOOK: the curves come back as polylines
// with NO source refs, so nothing can be dimensioned against them and a
// circle is a many-sided polygon rather than a circle. Never substituted for
// Exact when Exact is slow — the caller asks for it and the result says which
// it got.
enum class ProjectionMode { Exact, Poly };

struct ProjectedCurve {
  CurveKind kind = CurveKind::Sharp;
  bool visible = true;
  // Discretized points in the view plane (mm, model scale; X = right, Y = up
  // for the requested viewDir/up pair).
  std::vector<glm::dvec2> points;
  // The underlying curve's GeomAbs_CurveType as an int (0 = line, 1 = circle,
  // 2 = ellipse, ... 6+ = bspline/other) — lets dimensioning treat circles as
  // circles and the exporter emit arcs without this header pulling in OCC
  // enums.
  int curveType = -1;
  // For circle/ellipse intervals: the conic's center in view-plane mm and its
  // radius (major radius for ellipses). Zero/negative when not symbolic.
  glm::dvec2 conicCenter{0.0};
  double conicRadius = -1.0;
  // For conics: this interval sweeps the full circle/ellipse. A corner fillet
  // arc is NOT closed; a through-hole rim usually is — the hint dimensioning
  // needs to tell a bore from a rounded corner. Per-interval: a circle split
  // into visible+hidden halves yields two non-closed segments.
  bool closed = false;
  SourceRef source;
};

struct ProjectionResult {
  std::vector<ProjectedCurve> curves;
  // Which mode actually produced these. A caller that asked for Poly and got
  // it can say so on the sheet; nothing here ever silently downgrades.
  ProjectionMode mode = ProjectionMode::Exact;
  struct Stats {
    double updateMs = 0.0; // HLRBRep Update(): outline building
    double hideMs = 0.0;   // HLRBRep Hide(): visibility classification
    int dsEdges = 0;       // edges in the HLR data structure
    double selfMs = 0.0;
    double pairMs = 0.0;
    int selfCalls = 0;
    int pairCalls = 0;
    int selfHits = 0;
    int pairHits = 0;
    bool projectionHit = false;
    size_t cacheBytes = 0;     // payload only, excluding retained OCC geometry
    int unresolvedSources = 0; // curves whose SourceRef could not be traced
    // Where the hiding time went, per `InputBody::groupId` — the same two
    // clocks as selfMs/pairMs, attributed instead of summed, in the caller's
    // own ids.
    //
    // A PAIR's cost counts for BOTH of its members, because the question this
    // answers is "what would leaving this one out save", and leaving out
    // either member avoids that pair's work. So these overlap and their sum
    // exceeds selfMs + pairMs; a reader who normalises them is lying to
    // themselves (docs/drawings/README.md#what-a-view-costs).
    struct BodyCost {
      uint64_t sourceId = 0; // the group's id
      double ms = 0.0;
    };
    std::vector<BodyCost> costBySource;
  } stats;
};

class ProjectionCache;

struct ProjectionOptions {
  // Optional, session-local and single-threaded. Null is the reference path.
  ProjectionCache* cache = nullptr;
  ProjectionMode mode = ProjectionMode::Exact;
  bool hiddenLines = true;
  // Asked, as the hidden-line classification proceeds, whether to stop.
  // OCC's Hide() offers no such hook, so this is driven by running its
  // PAIRWISE form ourselves — see the .cpp. Null means run to completion.
  std::function<bool()> cancelled;
  // Max chord deviation for discretizing curved edges, in view-plane mm
  // (model scale — callers divide by view scale for sheet-mm control).
  double deflection = 0.05;
};

// Bounded runtime cache. No live documents or mutable OCC algorithms are kept.
// Caller must serialize access. Shapes are retained to prevent identity reuse.
class ProjectionCache {
public:
  struct Impl;
  ProjectionCache();
  ~ProjectionCache();
  ProjectionCache(ProjectionCache&&) noexcept;
  ProjectionCache& operator=(ProjectionCache&&) noexcept;
  ProjectionCache(const ProjectionCache&) = delete;
  ProjectionCache& operator=(const ProjectionCache&) = delete;
  void Clear();

private:
  std::unique_ptr<Impl> impl_;
  friend std::optional<ProjectionResult>
  ProjectView(const std::vector<InputBody>&, const glm::dvec3&,
              const glm::dvec3&, const ProjectionOptions&, std::string*);
};

// Projects `bodies` orthographically onto the plane normal to `viewDir`
// (the direction the viewer looks along), with `up` mapping to +Y. Runs one
// HLR pass across all bodies so occlusion is global. Returns std::nullopt and
// sets *error (when non-null) on failure — HLR exceptions are caught here,
// never propagated (per-view errors keep last-good geometry upstream).
std::optional<ProjectionResult>
ProjectView(const std::vector<InputBody>& bodies, const glm::dvec3& viewDir,
            const glm::dvec3& up, const ProjectionOptions& options,
            std::string* error);

// Where a world point lands in the view plane ProjectView draws into — the
// same frame, so anything drawn beside the projected curves (a bend line)
// lines up with them. Model mm, before the view's scale and position.
[[nodiscard]] glm::dvec2 ProjectPoint(const glm::dvec3& p,
                                      const glm::dvec3& viewDir,
                                      const glm::dvec3& up);

} // namespace drawing
