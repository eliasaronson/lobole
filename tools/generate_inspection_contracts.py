#!/usr/bin/env python3
"""Generate wire types and embedded schemas from the inspection contract.

Run with --check in CI. No running Designer or third-party packages required.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'api/inspection-contracts.json'


def generate():
    contract = json.loads(SOURCE.read_text())
    def check_schema(schema):
        supported = {'type', 'properties', 'required', 'additionalProperties',
                     'enum', 'minimum', 'maximum', 'minLength', 'items',
                     'minItems', 'maxItems', 'uniqueItems', 'default'}
        unknown = set(schema) - supported
        if unknown:
            raise ValueError(f'Unsupported schema keywords: {unknown}')
        if schema['type'] == 'object':
            if schema.get('additionalProperties') is not False:
                raise ValueError('Object contracts must reject unknown keys')
            for child in schema['properties'].values():
                check_schema(child)
        if schema['type'] == 'array':
            check_schema(schema['items'])
        if 'default' in schema:
            from designer_contracts import validate
            validate(schema, schema['default'], 'contract default')

    for spec in contract['methods'].values():
        check_schema(spec['request'])
        check_schema(spec['result'])
    wire = json.dumps(contract, sort_keys=True, separators=(',', ':'))
    digest = hashlib.sha256(wire.encode()).hexdigest()
    header = ('// Generated by tools/generate_inspection_contracts.py.\n'
              '#pragma once\n#include <string_view>\nnamespace remote {\n'
              f'inline constexpr std::string_view kInspectionContractHash =\n    "{digest}";\n'
              'inline constexpr const char* kInspectionContractJson =\n    R"contract('
              + wire + ')contract";\n} // namespace remote\n')
    records = []

    def typename(s, name, request=False):
        t = s['type']
        if 'enum' in s:
            return 'Literal[' + ', '.join(repr(x) for x in s['enum']) + ']'
        if t == 'object':
            props = []
            for key, spec in s['properties'].items():
                typ = typename(spec, name + ''.join(w.title() for w in key.split('_')), request)
                if key not in s.get('required', []):
                    typ = f'NotRequired[{typ}]'
                props.append(f'    {key}: {typ}')
            records.append(f'class {name}(TypedDict):\n' + '\n'.join(props))
            return name
        if t == 'array':
            typ = typename(s['items'], name + 'Item', request)
            return f'{"Sequence" if request else "list"}[{typ}]'
        return dict(string='str', integer='int', number='float', boolean='bool')[t]

    methods = []
    for method, specs in contract['methods'].items():
        title = ''.join(x.title() for x in method.split('_'))
        reqtype = typename(specs['request'], title + 'Request', True)
        resulttype = typename(specs['result'], title + 'Result')
        args, params = [], []
        for key, spec in specs['request']['properties'].items():
            typ = typename(spec, title + 'Argument' + ''.join(x.title() for x in key.split('_')), True)
            required = key in specs['request']['required']
            args.append(f'{key}: {typ}' + ('' if required else ' | None = None'))
            if required:
                params.append(f'        params[{key!r}] = {key}')
            else:
                params.append(f'        if {key} is not None:\n            params[{key!r}] = {key}')
        methods.append(f'    def {method}(self, *, ' + ', '.join(args) + f') -> {resulttype}:\n'
                       '        params: dict[str, object] = {}\n' + '\n'.join(params)
                       + f'\n        return cast({resulttype}, self._call({method!r}, params))')
    python = ('# Generated by tools/generate_inspection_contracts.py. Do not edit.\n'
              'from collections.abc import Callable, Sequence\n'
              'from typing import Literal, NotRequired, TypedDict, cast\n\n'
              + f'CONTRACT_VERSION = {contract["version"]}\nCONTRACT_HASH = {digest!r}\n\n'

              + '\n\n'.join(records) + '\n\n\nclass InspectionClient:\n'
              '    """Typed inspection facade; unknown RPCs use App.call explicitly."""\n\n'
              '    def __init__(self, call: Callable[[str, dict[str, object]], object]):\n'
              '        self._call = call\n\n' + '\n\n'.join(methods) + '\n')
    return {ROOT / 'src/remote/InspectionContracts.generated.h': header,
            ROOT / 'tools/designer_inspection.py': python}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, text in generate().items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text)
    if stale:
        parser.exit(1, 'Regenerate inspection contracts: ' + ', '.join(stale) + '\n')


if __name__ == '__main__':
    main()
